"""Conversational engine for the ``general_chat`` intent (roadmap step 4, option 2).

* If a fine-tuned model exists in ``models/chat`` (created by
  ``scripts/finetune_chat.py``), replies are generated by it with nucleus sampling.
* Otherwise - or if generation produces nothing usable - a small rule-based
  responder keeps the conversation going, so Jarvis works out of the box.
"""

from __future__ import annotations

import logging
import random
import re
from pathlib import Path
from typing import List, Optional, Sequence, Tuple

log = logging.getLogger(__name__)

# Movie scripts contain plenty of language a desk assistant shouldn't repeat.
_BLOCKLIST = re.compile(
    r"\b(?:fuck\w*|shit\w*|bitch\w*|bastard\w*|asshole\w*|dick\w*|cunt\w*|whore\w*|slut\w*|kill\w*|"
    r"murder\w*|gun\w*|die|dead|nigg\w*|fag\w*|retard\w*)\b", re.I)

_RULES: List[Tuple[re.Pattern, List[str]]] = [
    (re.compile(r"\bbored\b"), ["Want to hear a joke? Just say: tell me a joke.",
                                "We could look something up. Ask me about anything on Wikipedia."]),
    (re.compile(r"\b(?:sad|down|lonely|upset|unhappy)\b"),
     ["I'm sorry you're feeling that way. I'm here to talk, and it can really help to reach out to someone you trust."]),
    (re.compile(r"\b(?:stress\w*|nervous|anxious|worried|exams?|deadline)\b"),
     ["Take a breath. Break it into small steps, and I can set a reminder for each one if that helps."]),
    (re.compile(r"\b(?:tired|exhausted|sleepy|long day|can't sleep|cannot sleep)\b"),
     ["Sounds like you've earned a break. Want me to set a reminder so you can rest without worrying?"]),
    (re.compile(r"\b(?:happy|great|excited|good mood|wonderful|good day)\b"), ["That's great to hear!",
                                                                               "Glad to hear it."]),
    (re.compile(r"\b(?:hungry|food|eat|dinner|lunch)\b"),
     ["I can't cook, but I can remind you when the oven's done."]),
    (re.compile(r"\bfavou?rite\b"), ["I'm partial to well-commented code. What's yours?"]),
    (re.compile(r"\b(?:love you|like you)\b"), ["That's kind of you. I enjoy our conversations too."]),
    (re.compile(r"\bdo you (?:like|love|enjoy)\b"),
     ["I don't have tastes the way you do, but I'm curious. What do you like about it?"]),
    (re.compile(r"\b(?:sing|song)\b"), ["I'll spare you my singing. How about a joke instead?"]),
    (re.compile(r"\b(?:dream|sleep)\b"), ["I don't sleep. I just wait for you to say my name."]),
    (re.compile(r"\b(?:friends?)\b"), ["I'd like to think we're friends."]),
    (re.compile(r"\b(?:annoying|stupid|dumb|useless|weird)\b"),
     ["Sorry about that. I'm still learning. Tell me what went wrong and I'll try to do better."]),
    (re.compile(r"\b(?:smart|clever|awesome|funny|cool|amazing)\b"), ["Thank you. I learned from the best."]),
    (re.compile(r"\b(?:advice|motivate|motivation)\b"),
     ["Start small: pick one thing you can finish in the next twenty minutes. I can remind you when time's up."]),
    (re.compile(r"\baliens?\b"), ["The universe is very big. I'd keep an open mind."]),
    (re.compile(r"\bwhat do you think\b|\bopinion\b"),
     ["I don't really have opinions, but I can look it up on Wikipedia if you like."]),
    (re.compile(r"\bsecret\b"), ["Your secrets are safe with me. I only remember reminders."]),
    (re.compile(r"\b(?:busy|doing)\b"), ["Just waiting for your next request."]),
]


class ChatEngine:
    def __init__(self, model_dir: Optional[Path] = None, device: str = "auto", enabled: bool = True,
                 fallback_responses: Optional[Sequence[str]] = None, max_new_tokens: int = 40,
                 seed: Optional[int] = None):
        self._rng = random.Random(seed)
        self.fallback = list(fallback_responses or ["Interesting. Tell me more."])
        self.max_new_tokens = max_new_tokens
        self.model = None
        self.tokenizer = None
        self._device = None
        if enabled and model_dir and (Path(model_dir) / "config.json").exists():
            try:
                self._load(Path(model_dir), device)
            except Exception as exc:  # missing transformers, corrupt files, ...
                log.warning("Generative chat model could not be loaded (%s); using rule-based chat.", exc)

    @property
    def generative(self) -> bool:
        return self.model is not None

    def _load(self, model_dir: Path, device: str) -> None:
        from transformers import AutoModelForCausalLM, AutoTokenizer

        from ..device import get_torch_device

        self._device = get_torch_device(device)
        self.tokenizer = AutoTokenizer.from_pretrained(model_dir)
        if self.tokenizer.pad_token is None:
            self.tokenizer.pad_token = self.tokenizer.eos_token
        self.model = AutoModelForCausalLM.from_pretrained(model_dir).to(self._device).eval()
        log.info("Loaded generative chat model from %s on %s", model_dir, self._device)

    # -- public API ------------------------------------------------------------------------
    def reply(self, message: str, history: Sequence[Tuple[str, str]] = ()) -> str:
        if self.model is not None:
            for _ in range(2):  # sampling is random; give it a second chance
                text = self._generate(message, history)
                if text:
                    return text
        return self.rule_based(message)

    def rule_based(self, message: str) -> str:
        lowered = message.lower()
        for pattern, answers in _RULES:
            if pattern.search(lowered):
                return self._rng.choice(answers)
        return self._rng.choice(self.fallback)

    # -- generation ------------------------------------------------------------------------
    def _generate(self, message: str, history: Sequence[Tuple[str, str]]) -> str:
        import torch

        from .chat_training import format_prompt

        prompt = format_prompt(message, list(history)[-2:])
        inputs = self.tokenizer(prompt, return_tensors="pt").to(self._device)
        with torch.no_grad():
            output = self.model.generate(
                **inputs, max_new_tokens=self.max_new_tokens, do_sample=True, top_k=50, top_p=0.92,
                temperature=0.8, repetition_penalty=1.2, no_repeat_ngram_size=3,
                pad_token_id=self.tokenizer.pad_token_id, eos_token_id=self.tokenizer.eos_token_id)
        new_tokens = output[0][inputs["input_ids"].shape[1]:]
        return self._clean(self.tokenizer.decode(new_tokens, skip_special_tokens=True))

    @staticmethod
    def _clean(text: str) -> str:
        text = re.split(r"\n|User:|Jarvis:", text)[0].strip()
        if len(text) > 200:  # keep spoken replies short: cut at the last full sentence
            cut = max(text.rfind(p, 0, 200) for p in ".!?")
            text = text[: cut + 1] if cut > 0 else text[:200]
        if len(text.split()) < 2 or not re.search(r"[a-zA-Z]", text) or _BLOCKLIST.search(text):
            return ""
        return text
